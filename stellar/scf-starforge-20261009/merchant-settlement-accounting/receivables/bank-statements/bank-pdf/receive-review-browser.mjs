const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const need=(yes,message)=>{if(!yes)throw new Error(message);};
const encode=value=>Buffer.from(JSON.stringify(value)+'\n');
async function exists(file){try{return await fs.stat(file);}catch(error){if(error.code==='ENOENT')return null;throw error;}}
async function exact(file,bytes){
 bytes=Buffer.from(bytes);await fs.mkdir(path.dirname(file),{recursive:true,mode:0o700});
 try{await fs.writeFile(file,bytes,{flag:'wx',mode:0o600});}
 catch(error){if(error.code!=='EEXIST')throw error;need((await fs.readFile(file)).equals(bytes),'Preserve different retained output: '+file);}
 const returned=await fs.readFile(file);need(returned.equals(bytes),'Retained full output changed: '+file);
 return {file,bytes:bytes.length,sha256:sha(bytes)};
}
async function atomic(file,value){
 const tmp=file+'.next';await fs.writeFile(tmp,encode(value),{mode:0o600});
 const handle=await fs.open(tmp,'r');try{await handle.sync();}finally{await handle.close();}
 await fs.rename(tmp,file);
}
async function selected(file,limit){
 const bytes=await fs.readFile(file);need(bytes.length>0&&bytes.length<=limit,'Select the complete original file within its existing limit.');
 return {file:path.resolve(file),bytes:bytes.length,sha256:sha(bytes),content:bytes.toString('utf8')};
}
const onlyPin=row=>({file:row.file,bytes:row.bytes,sha256:row.sha256});
function material(desk){const copy=structuredClone(desk);delete copy.storageRevision;return canonical(copy);}
async function checkedDesk(text,issue){
 const desk=checkPdfDesk(JSON.parse(text));await openPdfReviewRecord(desk.record);
 need(desk.caseId===issue.reviewId&&desk.record.issue.sha256===issue.sha256,'The browser reopened a different named issue.');
 return desk;
}
/**
 * proposal is an explicit {action,value,actor,reason} against the actual issued
 * interpretation. currentWorkingCopyPath is the author's actual original copy.
 * decisionChoices maps every exact preview key to keep/adopt. No facts, choices,
 * accounts or financial receiving are generated by this course.
 *
 * The original owner must keep this context/profile, operation lease and output
 * directory across interrupted calls. A missing uncertain local mutation is
 * reported as CONTINUATION_REQUIRED, never replaced with another review.
 */
export async function receiveBankPdfNamedReviewBrowser({
 context,baseUrl,operationId,issuedReviewPath,currentWorkingCopyPath,sourceManifestPath,
 proposal,editionReviewer,editionComment,decisionAuthor,decisionReason,decisionChoices,
 outDirectory
}){
 need(context&&typeof context.newPage==='function','Supply the original receiver’s existing browser context.');
 need(typeof operationId==='string'&&operationId.length>0,'Retain the original receiver operation.');
 const target=new URL('/bank-statements/pdf/review.html',baseUrl);
 need(target.protocol==='http:'&&['127.0.0.1','localhost','[::1]'].includes(target.hostname),'Use the original local Bank service.');
 const issued=await selected(issuedReviewPath,384*1024*1024),current=await selected(currentWorkingCopyPath,192*1024*1024),sources=await selected(sourceManifestPath,16*1024*1024);
 const issue=await openPdfReviewIssue(issued.content),currentWork=await openWorkingCopy(current.content);
 need(currentWork.id===issue.source.workingCopyId&&currentWork.file.sha256===issue.source.pdf.sha256,'Select the same original current PDF.');
 need(proposal&&typeof proposal.action==='string'&&proposal.value!==undefined&&proposal.actor&&proposal.reason,'Supply the explicit original-engine proposal.');
 const items=proposal.action==='ROWS'?proposal.value:proposal.action==='PAGE_REVIEW'?[]:[proposal.value];
 need(Array.isArray(items)&&items.every(item=>item&&typeof item.id==='string'&&item.id),'Retain each original or deliberately selected new item ID before the original proposal.');
 need(editionReviewer&&typeof editionComment==='string'&&decisionAuthor&&decisionReason&&decisionReason.length<=4000,'Name the real reviewers and complete reasons.');
 need(decisionChoices&&typeof decisionChoices==='object','Supply every explicit author choice.');
 const request={schema:'stellar-forge.bank-pdf-named-review-browser-input.v1',operationId,url:target.href,
  issue:{file:issued.file,bytes:issued.bytes,sha256:issued.sha256},current:{file:current.file,bytes:current.bytes,sha256:current.sha256},
  sources:{file:sources.file,bytes:sources.bytes,sha256:sources.sha256},proposal,editionReviewer,editionComment,decisionAuthor,decisionReason,decisionChoices};
 outDirectory=path.resolve(outDirectory);await fs.mkdir(outDirectory,{recursive:true,mode:0o700});
 const requestPin=await exact(path.join(outDirectory,'original-input.json'),encode(request));
 const journalFile=path.join(outDirectory,'review-browser-journal.json');
 let journal=await exists(journalFile)?JSON.parse(await fs.readFile(journalFile,'utf8')):{
  schema:'stellar-forge.bank-pdf-named-review-browser-journal.v1',operationId,requestSha256:requestPin.sha256,
  issueSha256:issue.sha256,phases:[],active:null,screenshots:[],downloads:[],errors:[],state:'RECEIVING'};
 need(journal.operationId===operationId&&journal.requestSha256===requestPin.sha256&&journal.issueSha256===issue.sha256,'Retain the original exact browser course input.');
 const completeFile=path.join(outDirectory,'review-browser-result.json');
 if(await exists(completeFile)){
  const result=JSON.parse(await fs.readFile(completeFile,'utf8'));
  need(result.requestSha256===requestPin.sha256&&result.state==='COMPLETE','The retained completion belongs to another original request.');
  for(const pin of [...result.screenshots,...result.downloads]){const bytes=await fs.readFile(pin.file);need(bytes.length===pin.bytes&&sha(bytes)===pin.sha256,'A retained complete output changed: '+pin.file);}return result;
 }
 const attemptId=randomUUID(),attemptPrefix='attempts/'+attemptId+'/',attemptRoot=path.join(outDirectory,'attempts',attemptId);
 await fs.mkdir(attemptRoot,{recursive:true,mode:0o700});journal.attempts??=[];journal.attempts.push({id:attemptId,startedAt:new Date().toISOString(),directory:attemptRoot});
 const errorOffset=journal.errors.length;const pages=[];let page,primaryError,result;
 const save=()=>atomic(journalFile,journal);
 const idle=async()=>{await page.waitForFunction(()=>{const b=document.querySelector('#download-working');return b&&!b.disabled;},null,{timeout:180000});};
 const clean=async()=>{need(await page.locator('#message.error').count()===0,await page.locator('#message').innerText());};
 const download=async(selector,name)=>{
  const waiting=page.waitForEvent('download',{timeout:180000});await page.locator(selector).click();const item=await waiting;
  need(!(await item.failure()),'Original download failed: '+name);const source=await item.path();need(source,'The original browser download is unavailable.');
  const bytes=await fs.readFile(source),pin=await exact(path.join(outDirectory,name),bytes);
  if(!journal.downloads.some(row=>row.file===pin.file))journal.downloads.push({...pin,suggestedFilename:item.suggestedFilename()});
  return {...pin,content:bytes.toString('utf8')};
 };
 const snapshot=async name=>{
  const file=await download('#download-working',name),desk=await checkedDesk(file.content,issue);
  return {file,desk};
 };
 const observe=async()=>{
  const waiting=page.waitForEvent('download',{timeout:180000});await page.locator('#download-working').click();const item=await waiting;
  need(!(await item.failure()),'Could not retain the current complete browser working record.');
  return checkedDesk(await fs.readFile(await item.path(),'utf8'),issue);
 };
 const screenshot=async name=>{
  if(await page.locator('[data-panel="source"]').isVisible()){
   await page.waitForFunction(selected=>{const d=document.querySelector('#page-display'),label=document.querySelector('#page-label')?.textContent??'',number=label.match(/^Page (\d+) of /)?.[1];return d?.getAttribute('aria-busy')==='false'&&d.dataset.renderPage===number&&d.dataset.renderCase===selected.caseId&&d.dataset.renderSource===selected.sha256&&(d.dataset.renderState==='complete'||globalThis.__PDF_REVIEW_OFFLINE&&d.dataset.renderState==='browser-viewer');},{caseId:issue.reviewId,sha256:issue.source.pdf.sha256},{timeout:180000});
  }
  const file=path.join(attemptRoot,name+'.png');await page.screenshot({path:file,fullPage:true});const bytes=await fs.readFile(file);
  const pin={file,bytes:bytes.length,sha256:sha(bytes)};journal.screenshots.push(pin);await save();return pin;
 };
 const tab=async name=>{await page.locator('[data-tab="'+name+'"]').click();await idle();await clean();};
 const stage=async(name,predicate,work)=>{
  const prior=journal.phases.find(row=>row.name===name);
  if(prior){const retained=await selected(prior.record.file,PDF_DESK_MAX_BYTES);need(retained.bytes===prior.record.bytes&&retained.sha256===prior.record.sha256,'The complete original stage pin changed: '+name);const desk=await checkedDesk(retained.content,issue);need(await predicate(desk),'The retained original stage no longer satisfies its exact request: '+name);return desk;}
  const recordPath=path.join(outDirectory,name+'.working.json');
  if(await exists(recordPath)){
   const raw=await selected(recordPath,PDF_DESK_MAX_BYTES),desk=await checkedDesk(raw.content,issue);need(await predicate(desk),'Retained stage output does not satisfy its original request.');
   journal.phases.push({name,record:{file:raw.file,bytes:raw.bytes,sha256:raw.sha256},recovered:true});journal.active=null;await save();return desk;
  }
  let before=await observe();
  if(journal.active){
   need(journal.active.name===name,'Recover the earlier original local phase before continuing.');
   if(await predicate(before)){
    const retained=await snapshot(name+'.working.json');journal.phases.push({name,record:onlyPin(retained.file),recovered:true});journal.active=null;await save();return retained.desk;
   }
   need(sha(Buffer.from(material(before)))===journal.active.beforeSha256,'CONTINUATION_REQUIRED: preserve the original uncertain local phase and current draft; do not replay on another head.');
  }else{journal.active={name,beforeSha256:sha(Buffer.from(material(before))),at:new Date().toISOString()};await save();}
  await work(before);await idle();await clean();
  const after=await observe();need(await predicate(after),'Original browser phase did not retain the requested complete state: '+name);
  const retained=await snapshot(name+'.working.json');journal.phases.push({name,record:onlyPin(retained.file),completedAt:new Date().toISOString()});journal.active=null;await save();return retained.desk;
 };
 try{
  page=await context.newPage();pages.push(page);page.on('pageerror',error=>journal.errors.push({attemptId,message:String(error)}));page.on('dialog',dialog=>dialog.accept());
  await page.setViewportSize({width:1440,height:1000});await page.goto(target.href+'?case='+issue.reviewId,{waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>document.querySelector('#open-file-button')&&!document.querySelector('#open-file-button').disabled,null,{timeout:180000});
  const hostSources=await page.evaluate(async()=>{const r=await fetch('./review-source.json',{cache:'no-store'});if(!r.ok)throw Error('Complete review source unavailable');return r.json();});
  need(canonical(hostSources)===canonical(JSON.parse(sources.content)),'The actual served PDF review source differs from the selected whole source manifest.');
  if(!(await page.locator('#case-content').isVisible())){
   need(!journal.active,'CONTINUATION_REQUIRED: the original browser has an unresolved mutation and its saved case is unavailable.');
   const latest=journal.phases.at(-1)?.record.file??issued.file;
   await screenshot('review-empty');await page.locator('#open-file').setInputFiles(latest);await page.locator('#open-file-button').click();await idle();await clean();
  }
  const opened=await observe();need(opened.record.issue.sha256===issue.sha256,'The current page is not the original issued review.');
  if(!journal.phases.length)await stage('issue-open',desk=>desk.record.issue.sha256===issue.sha256,async()=>{});
  // Exercise the guided path with the exact existing account, without adding a
  // financial fact or applying an extra model edit. Preserve the form and its
  // retained advanced draft before continuing the explicitly supplied proposal.
  const guidedAccount=issue.workingCopy.accounts[0];
  if(guidedAccount){
   const guidedRaw=JSON.stringify({action:'ACCOUNT',value:guidedAccount},null,2);
   const guidedDraftMatches=d=>d.ui?.guidedDraft?.collection==='accounts'&&d.ui.guidedDraft.baseRevision===issue.workingCopy.revision&&canonical(d.ui.guidedDraft.value)===canonical(guidedAccount)&&d.ui.guidedDraft.dirty;
   await stage('recipient-guided-form',guidedDraftMatches,async()=>{
    await tab('source');await page.locator('#collection').selectOption('accounts');await idle();
    while((await observe()).ui.itemOffset>0){await page.locator('#previous-item').click();await idle();}
    const editButtons=page.locator('[data-action="edit"]'),editIndex=await editButtons.evaluateAll((nodes,id)=>nodes.findIndex(node=>node.dataset.id===id),guidedAccount.id);
    need(editIndex>=0,'The original guided account edit button is unavailable.');await editButtons.nth(editIndex).click();await idle();
    await page.locator('#guided-editor [data-focus="Account name"]').fill(guidedAccount.name);
    await page.locator('#guided-editor [data-focus="Account interpretation note"]').fill(guidedAccount.note);
    await tab('editions');await tab('source');await page.reload({waitUntil:'domcontentloaded'});await idle();await clean();
    await screenshot('guided-account-reopened');
   });
   const retainedGuided=d=>d.record.draft.rawDirty&&d.record.draft.raw===guidedRaw&&(d.ui?.guidedDraftHistory??[]).some(x=>x.collection==='accounts'&&canonical(x.value)===canonical(guidedAccount));
   await stage('recipient-guided-retained',retainedGuided,async()=>{
    await tab('source');await page.locator('#guided-editor [data-focus="retain-edit"]').click();await idle();await tab('editions');await tab('source');
   });
   await stage('recipient-guided-preserved',d=>!d.record.draft.rawDirty&&(d.ui?.guidedDraftHistory??[]).some(x=>x.collection==='accounts'&&canonical(x.value)===canonical(guidedAccount)),async()=>{
    await tab('source');await page.locator('#discard-raw').click();await idle();
   });
  }
  const rawEdit=JSON.stringify({action:proposal.action,value:proposal.value},null,2);
  await stage('recipient-raw-draft',d=>d.record.draft.raw===rawEdit&&d.record.draft.rawDirty&&d.record.draft.reviewer===proposal.actor&&d.ui.editReason===proposal.reason,async()=>{
   await tab('source');await page.locator('#advanced-edit').evaluate(element=>{element.open=true;});await page.locator('#reviewer').fill(proposal.actor);await page.locator('#edit-reason').fill(proposal.reason);await page.locator('#raw-edit').fill(rawEdit);
   // A normal tab operation drains coalesced fields before reloading the same case.
   await tab('editions');await tab('source');await page.reload({waitUntil:'domcontentloaded'});await idle();await clean();
  });
  const proposed=editWorkingCopy(issue.workingCopy,proposal.action,proposal.value,{actor:proposal.actor,reason:proposal.reason});
  const proposalMatches=async desk=>{
   const actual=await pdfReviewWorkingCopy(desk.record),expected=structuredClone(proposed);
   if(actual.history.length!==expected.history.length)return false;
   expected.history.at(-1).at=actual.history.at(-1).at;
   return canonical(actual)===canonical(expected)&&!desk.record.draft.rawDirty;
  };
  await stage('recipient-proposal',proposalMatches,async()=>{
   await tab('source');await page.locator('#interpretation-form button[type=submit]').click();
  });
  await stage('recipient-submitted',desk=>desk.record.editions.some(e=>e.status==='submitted'&&e.reviewer===editionReviewer&&e.comment===editionComment),async()=>{
   await tab('editions');await page.locator('#edition-status').selectOption('submitted');await page.locator('#edition-reviewer').fill(editionReviewer);
   await page.locator('#edition-comment').fill(editionComment);await page.locator('#edition-form button[type=submit]').click();
  });
  let desk=await observe(),submitted=desk.record.editions.find(e=>e.status==='submitted'&&e.reviewer===editionReviewer&&e.comment===editionComment);
  need(submitted,'The original submitted edition is missing.');
  await tab('editions');
  const returnedFile=await download('[data-action="edition-return"][data-id="'+submitted.editionId+'"]','original-submitted-return.json');
  const returned=await openPdfReviewReturn(returnedFile.content,{issue});
  await stage('author-return',d=>d.returns.some(row=>row.sha256===returnedFile.sha256),async()=>{
   await tab('author');await page.locator('#return-file').setInputFiles(returnedFile.file);await page.locator('#receive-return').click();
  });
  await stage('author-current',d=>canonical(d.currentWorkingCopy)===canonical(currentWork),async()=>{
   await tab('author');await page.locator('#current-file').setInputFiles(current.file);await page.locator('#receive-current').click();
  });
  const expectedPreview=await previewPdfReviewReturn({issue,returned,currentWorkingCopy:currentWork});
  need(Object.keys(decisionChoices).length===expectedPreview.changes.length&&expectedPreview.changes.every(row=>['keep','adopt'].includes(decisionChoices[row.key])),'Supply every exact actual comparison key and author choice.');
  await stage('author-comparison',d=>d.ui.preview?.sha256===expectedPreview.sha256,async()=>{await tab('author');await page.locator('#compare').click();});
  await stage('author-decision',d=>d.decisions.some(row=>row.decision.previewSha256===expectedPreview.sha256&&canonical(row.decision.choices)===canonical(decisionChoices)&&row.decision.author===decisionAuthor&&row.decision.reason===decisionReason),async()=>{
   await tab('author');
   for(let offset=0;offset<expectedPreview.changes.length;offset+=20){
    for(const row of expectedPreview.changes.slice(offset,offset+20))await page.locator('select[data-choice]').evaluateAll((nodes,selection)=>{const node=nodes.find(n=>n.dataset.choice===selection.key);if(!node)throw Error('Original comparison field missing');node.value=selection.value;node.dispatchEvent(new Event('change',{bubbles:true}));},{key:row.key,value:decisionChoices[row.key]});
    if(offset+20<expectedPreview.changes.length){await page.locator('#next-change').click();await idle();}
   }
   await page.locator('#decision-author').fill(decisionAuthor);await page.locator('#decision-reason').fill(decisionReason);await page.locator('#decision-form button[type=submit]').click();
  });
  desk=await observe();const chosen=desk.decisions.find(row=>row.decision.previewSha256===expectedPreview.sha256&&row.decision.author===decisionAuthor&&row.decision.reason===decisionReason);
  const replay=await applyPdfReviewDecision({issue,returned,currentWorkingCopy:currentWork,decision:chosen.decision});
  need(canonical(replay.workingCopy)===canonical(chosen.workingCopy),'The downloaded author result differs from the original engine decision.');
  await tab('source');
  while((await observe()).ui.page>1){await page.locator('#previous-page').click();await idle();}
  for(let number=1;number<=issue.workingCopy.extraction.pages.length;number++){
   if(number>1){await page.locator('#next-page').click();await idle();}
   await page.waitForFunction(selected=>{const d=document.querySelector('#page-display');return d?.dataset.renderState==='complete'&&d.dataset.renderPage===String(selected.page)&&d.dataset.renderCase===selected.caseId&&d.dataset.renderSource===selected.sha256&&d.getAttribute('aria-busy')==='false';},{page:number,caseId:issue.reviewId,sha256:issue.source.pdf.sha256},{timeout:180000});
   await screenshot('review-original-page-'+String(number).padStart(3,'0'));
  }
  for(const name of ['source','editions','author','recovery']){await tab(name);await screenshot('review-'+name+'-desktop');}
  await page.setViewportSize({width:390,height:844});
  for(const name of ['source','editions','author','recovery']){await tab(name);need(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2),'The narrow review desk overflows.');await screenshot('review-'+name+'-390');}
  await tab('source');await download('#download-pdf',attemptPrefix+'complete-original.pdf');
  const finalRecord=await snapshot(attemptPrefix+'complete-review.working.json'),html=await download('#download-html',attemptPrefix+'complete-offline-review.html'),project=await download('#download-project',attemptPrefix+'complete-source-project.json');
  need(canonical(JSON.parse(project.content).desk)===canonical(finalRecord.desk),'The complete project differs from the exact current working record.');
  const offlinePage=await context.newPage();pages.push(offlinePage);offlinePage.on('pageerror',error=>journal.errors.push({attemptId,message:String(error)}));offlinePage.on('dialog',dialog=>dialog.accept());await offlinePage.goto(pathToFileURL(html.file).href,{waitUntil:'domcontentloaded'});
  await offlinePage.locator('#case-content').waitFor({state:'visible',timeout:180000});await offlinePage.waitForFunction(()=>!document.querySelector('#download-working').disabled);
  const previous=page;page=offlinePage;await page.setViewportSize({width:390,height:844});await clean();
  const reopened=await snapshot(attemptPrefix+'offline-reopened.working.json');
  need(canonical(reopened.desk.record)===canonical(finalRecord.desk.record)&&canonical(reopened.desk.decisions)===canonical(finalRecord.desk.decisions),'Offline reopening changed the full interpretation or author decisions.');
  await screenshot('offline-review-390');page=previous;
  need(journal.errors.length===errorOffset,'The current review attempt encountered browser errors: '+journal.errors.slice(errorOffset).map(row=>row.message).join('; '));
  result={schema:'stellar-forge.bank-pdf-named-review-browser-result.v1',state:'COMPLETE',operationId,requestSha256:requestPin.sha256,reviewId:issue.reviewId,issueSha256:issue.sha256,
   completedAttempt:attemptId,attempts:journal.attempts,diagnostics:journal.errors,completedAttemptErrors:journal.errors.slice(errorOffset),originalPdf:issue.source.pdf,originalPages:issue.workingCopy.extraction.pages.length,recipientEditionId:submitted.editionId,decisionId:chosen.decision.decisionId,resultingRevision:chosen.workingCopy.revision,
   phases:journal.phases,screenshots:journal.screenshots,downloads:journal.downloads,
   renderedInspection:'Screens were captured. The original receiving owner must actually view these and use/open all outgoing artifacts before customer readiness.',
   financialReceiving:'SEPARATE_ORIGINAL_BANK_OPERATION'};
 }catch(error){primaryError=error;journal.lastError={name:error.name,message:error.message,at:new Date().toISOString()};await save().catch(saveError=>{error.journalError=String(saveError);});}
 const stillOwned=new Set(pages),closeOriginal=async()=>{const failures=[];for(const owned of [...stillOwned].reverse())try{await owned.close();stillOwned.delete(owned);}catch(error){failures.push(String(error));}if(failures.length)throw Object.assign(new Error('The original review pages did not close.'),{closeErrors:failures});};
 let closeFailure;try{await closeOriginal();}catch(error){closeFailure=error;}
 if(primaryError||closeFailure){const error=primaryError??closeFailure;if(closeFailure)error.closeErrors=closeFailure.closeErrors;throw Object.assign(error,{journalFile,outDirectory,close:closeOriginal});}
 await exact(completeFile,encode(result));journal.state='COMPLETE';journal.completedAt=new Date().toISOString();await save();return result;
}
