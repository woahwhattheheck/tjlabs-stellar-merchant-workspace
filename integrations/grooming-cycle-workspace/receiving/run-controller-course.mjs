import fs from "node:fs/promises";
import path from "node:path";
import {fileURLToPath} from "node:url";
import {runGroomControllerCourse} from "./controller-course.mjs";
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const out=process.argv[2];if(!out)throw Error("Usage: node receiving/run-controller-course.mjs NEW_DIRECTORY");
const names=["vendor/archive-codec.js","groom-cycle-core.js","workbench/groom-workspace.js","workbench/operator.js"];
const files=Object.fromEntries(await Promise.all(names.map(async name=>[name,await fs.readFile(path.join(root,name),"utf8")])));
const blank=JSON.parse(await fs.readFile(path.join(root,"examples/blank-desk.json"),"utf8"));
const worked=JSON.parse(await fs.readFile(path.join(root,"examples/worked-desk.json"),"utf8"));
const result=await runGroomControllerCourse({files,blank,worked});
await fs.mkdir(out,{recursive:false});await fs.writeFile(path.join(out,"controller-result.json"),JSON.stringify(result,null,2)+"\n",{flag:"wx"});
console.log(JSON.stringify({checks:result.checks.length,out}));
