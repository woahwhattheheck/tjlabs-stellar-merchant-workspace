import fs from "node:fs/promises";
import path from "node:path";
import {createArchiveCodec} from "../vendor/archive-codec.mjs";
import {createGroomCycleCore} from "../groom-cycle-core.mjs";
import {runGroomCycleCLI} from "../groom-cycle-native.mjs";
import {receiveGroomCycleNative} from "./groom-native-receiving.mjs";
if(process.argv.length!==4||process.argv[2]!=="--out")throw Error("Use --out NEW_DIRECTORY");
const codec=createArchiveCodec(),core=createGroomCycleCore({codec});
const modelSource=await fs.readFile(new URL("../workbench/groom-workspace.js",import.meta.url),"utf8");
const workspaceAPI=new Function(modelSource+";return createGroomCycleWorkspace;")()(core,codec);
const desk=JSON.parse(await fs.readFile(new URL("../examples/worked-desk.json",import.meta.url),"utf8"));
const result=await receiveGroomCycleNative({fs,path,codec,core,workspaceAPI,runCLI:runGroomCycleCLI,directory:path.resolve(process.argv[3]),desk});
await fs.writeFile(path.join(path.resolve(process.argv[3]),"receiving-result.json"),JSON.stringify(result,null,2)+"\n",{flag:"wx"});
console.log(JSON.stringify({summary:result.summary,checks:result.checks},null,2));
