import fs from "node:fs/promises";
import path from "node:path";
import {fileURLToPath} from "node:url";
import {createArchiveCodec} from "../vendor/archive-codec.mjs";
import {createDeliverySlotCore} from "../delivery-slot-core.mjs";
import {runDeliverySlotCLI} from "../delivery-slot-native.mjs";
import {receiveDeliveryNative} from "./native-course.mjs";
const root=fileURLToPath(new URL("../",import.meta.url)),codec=createArchiveCodec(),core=createDeliverySlotCore({codec});
const source=await fs.readFile(path.join(root,"workbench/delivery-workspace.js"),"utf8");
const createWorkspace=new Function(source+";return createDeliverySlotWorkspace;")();
const workspaceAPI=createWorkspace(core,codec),desk=JSON.parse(await fs.readFile(path.join(root,"examples/worked-desk.json"),"utf8"));
const directory=process.argv[2];if(!directory)throw Error("Pass a NEW output directory");
const result=await receiveDeliveryNative({fs,path,codec,core,workspaceAPI,runCLI:runDeliverySlotCLI,directory,desk});
await fs.writeFile(path.join(directory,"RECEIVING_RESULT.json"),JSON.stringify(result,null,2)+"\n",{flag:"wx"});
console.log(JSON.stringify({schema:result.schema,checks:result.checks,summary:result.summary},null,2));
