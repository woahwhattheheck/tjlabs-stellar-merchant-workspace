import fs from "node:fs/promises";
import path from "node:path";
import {createArchiveCodec} from "../vendor/archive-codec.mjs";
import {createMarineJobCore} from "../marine-job-core.mjs";
import {runMarineJobCLI} from "../marine-job-native.mjs";
import {receiveMarineJobNative} from "./marine-native-receiving.mjs";
if(process.argv.length!==4||process.argv[2]!=="--out")throw Error("Use --out NEW_DIRECTORY");
const codec=createArchiveCodec(),core=createMarineJobCore({codec});
const modelSource=await fs.readFile(new URL("../workbench/marine-workspace.js",import.meta.url),"utf8");
const workspaceAPI=new Function(modelSource+";return createMarineJobWorkspace;")()(core,codec);
const desk=JSON.parse(await fs.readFile(new URL("../examples/worked-desk.json",import.meta.url),"utf8"));
const result=await receiveMarineJobNative({fs,path,codec,core,workspaceAPI,runCLI:runMarineJobCLI,directory:path.resolve(process.argv[3]),desk});
await fs.writeFile(path.join(path.resolve(process.argv[3]),"receiving-result.json"),JSON.stringify(result,null,2)+"\n",{flag:"wx"});
console.log(JSON.stringify({summary:result.summary,checks:result.checks},null,2));
